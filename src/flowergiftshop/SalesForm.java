    private void btnSellActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSellActionPerformed
        if (cmbCustomer.getSelectedItem() == null) {
    JOptionPane.showMessageDialog(this, "Please select a customer.");
    return;
}

if (cmbProduct.getSelectedItem() == null) {
    JOptionPane.showMessageDialog(this, "Please select a product.");
    return;
}
        try {
    int customerId = Integer.parseInt(
    cmbCustomer.getSelectedItem().toString().split(" - ")[0]
);

int productId = Integer.parseInt(
    cmbProduct.getSelectedItem().toString().split(" - ")[0]
);
    String quantityText = txtQuantity.getText().trim();

if (quantityText.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please enter quantity.");
    return;
}

int quantity = Integer.parseInt(quantityText);

if (quantity <= 0) {
    throw new InvalidQuantityException("Quantity must be greater than 0.");
}
java.sql.Connection stockCon =
    flowergiftshop.dao.DatabaseConnection.getConnection();

String stockSql =
    "SELECT quantity FROM products WHERE product_id=?";

java.sql.PreparedStatement stockPst =
    stockCon.prepareStatement(stockSql);

stockPst.setInt(1, productId);

java.sql.ResultSet stockRs =
    stockPst.executeQuery();

int availableStock = 0;

if (stockRs.next()) {
    availableStock = stockRs.getInt("quantity");
}

if (quantity > availableStock) {
    JOptionPane.showMessageDialog(
        this,
        "Not enough stock! Available stock: " + availableStock
    );

    stockRs.close();
    stockPst.close();
    stockCon.close();
    return;
}

stockRs.close();
stockPst.close();
stockCon.close();
   
    double totalPrice = Double.parseDouble(txtTotalPrice.getText());

    java.sql.Connection con =
    flowergiftshop.dao.DatabaseConnection.getConnection();

    String sql = "INSERT INTO sales (customer_id, product_id, quantity, total_price) VALUES (?, ?, ?, ?)";

    java.sql.PreparedStatement pst = con.prepareStatement(sql);
    pst.setInt(1, customerId);
    pst.setInt(2, productId);
    pst.setInt(3, quantity);
    pst.setDouble(4, totalPrice);

    pst.executeUpdate();
    String updateStockSql =
    "UPDATE products SET quantity = quantity - ? WHERE product_id=?";

java.sql.PreparedStatement updateStockPst =
    con.prepareStatement(updateStockSql);

updateStockPst.setInt(1, quantity);
updateStockPst.setInt(2, productId);

updateStockPst.executeUpdate();

updateStockPst.close();

    JOptionPane.showMessageDialog(this, "Sale Added Successfully!");

    con.close();
        
        } catch (InvalidQuantityException e) {
    JOptionPane.showMessageDialog(this, e.getMessage());

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnSellActionPerformed

    private void cmbProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbProductActionPerformed
                                           
                                          
    try {
        String selectedProduct = cmbProduct.getSelectedItem().toString();

        int productId = Integer.parseInt(
            selectedProduct.split(" - ")[0]
        );

       java.sql.Connection con =
    flowergiftshop.dao.DatabaseConnection.getConnection();

        String sql = "SELECT price FROM products WHERE product_id=?";
        java.sql.PreparedStatement pst = con.prepareStatement(sql);
        pst.setInt(1, productId);

        java.sql.ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            selectedProductPrice = rs.getDouble("price");
            txtTotalPrice.setText(String.valueOf(selectedProductPrice)); 
        }

        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_cmbProductActionPerformed

    private void txtQuantityKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtQuantityKeyReleased
      try {
    int quantity = Integer.parseInt(txtQuantity.getText().trim());

    double total = selectedProductPrice * quantity;

    txtTotalPrice.setText(String.valueOf(total));

} catch (NumberFormatException e) {
    txtTotalPrice.setText("");
}
    }//GEN-LAST:event_txtQuantityKeyReleased

