private void loadCustomers() {
    try {
        java.sql.Connection con =
    flowergiftshop.dao.DatabaseConnection.getConnection();

        String sql = "SELECT customer_id, name FROM customers";

        java.sql.PreparedStatement pst = con.prepareStatement(sql);
        java.sql.ResultSet rs = pst.executeQuery();

        cmbCustomer.removeAllItems();

        while (rs.next()) {
            cmbCustomer.addItem(
                rs.getInt("customer_id") + " - " + rs.getString("name")
            );
        }

        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}
private void loadProducts() {
    try {
        java.sql.Connection con =
    flowergiftshop.dao.DatabaseConnection.getConnection();

        String sql = "SELECT product_id, product_name FROM products";

        java.sql.PreparedStatement pst = con.prepareStatement(sql);
        java.sql.ResultSet rs = pst.executeQuery();

        cmbProduct.removeAllItems();

        while (rs.next()) {
            cmbProduct.addItem(
                rs.getInt("product_id") + " - " + rs.getString("product_name")
            );
        }

        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}

